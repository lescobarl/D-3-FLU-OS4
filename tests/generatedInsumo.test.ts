// ============================================================
// generatedInsumo — Guard del INSUMO de un artefacto GENERADO por FLU
// ------------------------------------------------------------
// Un artefacto generado (carta/documento, guion de video) debe dejar su CUERPO
// en el historial de conversacion para que FLU lo pueda explicar/referir y
// llegue a la minuta (P8.82). Hermano de imageInsumo/documentInsumo.
// ============================================================
import { describe, expect, it } from 'vitest';
import { buildGeneratedInsumo } from '../src/core/documents/generatedInsumo';

const CARTA = {
    text: 'Querida familia: les escribo desde el viaje.',
    nombre: 'Carta a la familia',
};

describe('generatedInsumo — insumo de lo GENERADO por FLU', () => {
    it('el cuerpo generado compone el insumo, con el titulo como contexto', () => {
        const out = buildGeneratedInsumo(CARTA, 'es');
        expect(out, 'una carta con cuerpo NO puede quedarse sin insumo').toBeTruthy();
        expect(out).toContain('Querida familia');
        expect(out).toContain('Carta a la familia');
    });

    it('sin titulo, el insumo sigue llevando el cuerpo', () => {
        const out = buildGeneratedInsumo({ text: 'Guion del video.' }, 'es');
        expect(out).toContain('Guion del video');
    });

    it('con la app en INGLES la etiqueta es inglesa', () => {
        expect(String(buildGeneratedInsumo(CARTA, 'en'))).toMatch(/document generated by flu/i);
    });

    it('SIN cuerpo legible no hay insumo (no se inventa contenido)', () => {
        // Un resultado SIN `text` (p. ej. un binario) no aporta cuerpo legible.
        expect(buildGeneratedInsumo({ nombre: 'documento.pdf' })).toBeNull();
        expect(buildGeneratedInsumo({ text: '   ' })).toBeNull();
        expect(buildGeneratedInsumo(null)).toBeNull();
        expect(buildGeneratedInsumo(undefined)).toBeNull();
    });
});

// Prueba de DETECTOR: el predicado del guard discrimina (no es decorativo).
describe('generatedInsumo — el detector no es decorativo', () => {
    it('marca la entrada con cuerpo real y perdona la que no trae texto', () => {
        const hayInsumo = (r: { text?: string; nombre?: string } | null) =>
            buildGeneratedInsumo(r) !== null;
        expect(hayInsumo({ text: 'cuerpo real generado' })).toBe(true);
        expect(hayInsumo({ nombre: 'documento.pdf' })).toBe(false);
    });
});
